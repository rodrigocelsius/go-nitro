// resource-crud — full CRUD from one app.Resource call over a BLinq store:
//
//	GET    /products?name=&active=true&min_price=10&q=chair&sort=-price&page=2&per_page=20
//	GET    /products/:id
//	POST   /products            (validated, transform: trim / titlecase)
//	PATCH  /products/:id        (merge: only the sent fields change)
//	DELETE /products/:id        (soft delete: deleted_at)
//	GET    /products/queries/stats   (dashboard counters, no raw SQL)
//
// CategoryName is denormalized: computed:"true" (clients cannot write it) and
// filled in BeforeWrite from the category — atomically with the write.
//
//	cd examples/v2/resource-crud && go test . && go run .
//
// In an app generated by the CLI the column handles below come from
// `nitrogen make internal/model/product.go --data` (package modelgen).
package main

import (
	"context"
	"embed"
	"log"

	"github.com/rodrigocelsius/go-nitro/blinq/v2/field"
	sqladapter "github.com/rodrigocelsius/go-nitro/data/adapter/sql/v2"
	nitro "github.com/rodrigocelsius/go-nitro/pkg/v2"
)

//go:embed migrations/*.sql
var migrations embed.FS

type Category struct {
	nitro.Model
	Name string `json:"name" validate:"required" transform:"trim,titlecase"`
}

type Product struct {
	nitro.Model
	Name         string      `json:"name" validate:"required,min=2" transform:"trim"`
	SKU          string      `json:"sku" validate:"required" transform:"trim,upper"`
	Price        float64     `json:"price" validate:"gt=0"`
	Stock        int         `json:"stock" validate:"gte=0"`
	Active       bool        `json:"active"`
	CategoryID   *nitro.UUID `json:"category_id"`
	CategoryName string      `json:"category_name" computed:"true"`
	// nitro.Model has DeletedAt: DELETE is a soft delete, lists hide deleted rows.
}

// Column handles (what `nitrogen make … --data` generates as modelgen.Products).
var cols = struct {
	Active field.Field[bool]
	Stock  field.Field[int]
	Price  field.Field[float64]
}{
	Active: field.Col[bool]("products", "active"),
	Stock:  field.Col[int]("products", "stock"),
	Price:  field.Col[float64]("products", "price"),
}

// Stats is the dashboard payload.
type Stats struct {
	Total      int   `json:"total"`
	Active     int   `json:"active"`
	OutOfStock int   `json:"out_of_stock"`
	Units      int64 `json:"units"`
}

func newApp(db *sqladapter.DB) *nitro.App {
	app := nitro.New(nitro.Config{DisableDefaults: true})
	categories := sqladapter.StoreFor[Category](db)
	products := sqladapter.StoreFor[Product](db)

	app.Resource(&Category{}, categories, &nitro.ResourceConfig{Public: true})
	app.Resource(&Product{}, products, &nitro.ResourceConfig{
		Public:      true, // demo: see examples/v2/business-commands for JWT by default
		DefaultSort: "-created_at",
		Filterable:  []string{"name", "active", "category_id"},
		Sortable:    []string{"name", "price", "stock", "created_at"},
		FilterRules: []nitro.FilterRule{
			{Param: "q", Field: "name", Op: "icontains"},
			{Param: "min_price", Field: "price", Op: "gte"},
			{Param: "max_price", Field: "price", Op: "lte"},
		},
		BeforeWrite: func(ctx context.Context, e any) error {
			p := e.(*Product)
			p.CategoryName = ""
			return nitro.FillStringFrom(ctx, categories, p.CategoryID, &p.CategoryName, func(c *Category) string { return c.Name })
		},
		Queries: nitro.Queries(nitro.Q("stats", func(ctx context.Context, _ nitro.Page) (*Stats, error) {
			var s Stats
			var err error
			if s.Total, err = products.CountAll(ctx); err != nil {
				return nil, err
			}
			if s.Active, err = products.CountWhere(ctx, cols.Active.Eq(true)); err != nil {
				return nil, err
			}
			if s.OutOfStock, err = products.CountWhere(ctx, cols.Stock.Eq(0)); err != nil {
				return nil, err
			}
			s.Units, err = products.SumInt64(ctx, cols.Stock.Ref())
			return &s, err
		})),
	})
	return app
}

func main() {
	ctx := context.Background()
	var db *sqladapter.DB
	var err error
	if sqladapter.EnvDSN() == "" {
		db, err = sqladapter.Open(ctx, "sqlite", "file:data/products.db")
	} else {
		db, err = sqladapter.OpenEnv(ctx)
	}
	if err != nil {
		log.Fatal(err)
	}
	defer db.Close()
	if err := db.MigrateFS(ctx, migrations); err != nil {
		log.Fatal(err)
	}
	nitro.Ok(newApp(db).Listen(":8080"))
}
