package main

import (
	"fmt"
	"os"
	"path/filepath"
	"strings"

	openapi "github.com/rodrigocelsius/go-nitro/codegen/openapi/v2"
)

func cmdOpenAPI(args []string) {
	root := "."
	out := "openapi.json"
	title := "API"
	version := "0.1.0"
	desc := "Generated by nitrogen openapi"
	bearer := false
	for i := 0; i < len(args); i++ {
		switch args[i] {
		case "--dir":
			if i+1 < len(args) {
				root = args[i+1]
				i++
			}
		case "-o", "--out":
			if i+1 < len(args) {
				out = args[i+1]
				i++
			}
		case "--title":
			if i+1 < len(args) {
				title = args[i+1]
				i++
			}
		case "--version":
			if i+1 < len(args) {
				version = args[i+1]
				i++
			}
		case "--desc", "--description":
			if i+1 < len(args) {
				desc = args[i+1]
				i++
			}
		case "--bearer":
			bearer = true
		case "-h", "--help":
			fmt.Println(`usage: nitrogen openapi [--dir .] [-o openapi.json] [--title API] [--version 0.1.0] [--bearer]

Scans Get/Post/Resource/AuthRoutes like nitrogen routes and writes OpenAPI 3 JSON.
At runtime prefer app.OpenAPI(...) / app.Swagger(...) after registering routes.`)
			return
		}
	}

	if mod := modulePath(); mod != "" {
		if parts := strings.Split(mod, "/"); len(parts) > 0 {
			last := parts[len(parts)-1]
			if title == "API" && last != "" {
				title = last
			}
		}
	}

	routes := scanProjectRoutes(root)
	if len(routes) == 0 {
		fmt.Fprintln(os.Stderr, "nitrogen: no routes found — register Resource/handlers first")
		fmt.Fprintln(os.Stderr, "nitrogen: tip — nitrogen routes ; or app.OpenAPI at runtime")
		os.Exit(1)
	}

	gen := openapi.NewGenerator(title, desc, version)
	gen.AddServer("http://127.0.0.1:8080", "local")
	gen.UseErrorSchema()
	schemas := newSchemaBuilder(root, gen)
	if bearer {
		gen.AddBearerAuth("")
	}

	seen := map[string]bool{}
	for _, r := range routes {
		key := r.method + " " + r.path
		if seen[key] {
			continue
		}
		seen[key] = true
		info := openapi.RouteInfo{
			Method:  r.method,
			Path:    r.path,
			Summary: r.method + " " + r.path,
			Tags:    []string{tagFromPath(r.path)},
			Params:  pathParams(r.path),
		}
		if bearer && looksProtected(r.path) {
			info.Security = openapi.BearerAuth()
		}
		if r.model != "" {
			if rs, ok := schemas.resource(r.model); ok {
				describeResourceRoute(&info, rs)
			}
		}
		gen.AddRoute(info)
	}

	raw, err := gen.Generate()
	if err != nil {
		fmt.Fprintf(os.Stderr, "nitrogen: openapi: %v\n", err)
		os.Exit(1)
	}
	if err := os.MkdirAll(filepath.Dir(out), 0755); err != nil && filepath.Dir(out) != "." {
		fmt.Fprintf(os.Stderr, "nitrogen: %v\n", err)
		os.Exit(1)
	}
	if err := writeFileFmt(out, raw, 0644); err != nil {
		fmt.Fprintf(os.Stderr, "nitrogen: write %s: %v\n", out, err)
		os.Exit(1)
	}
	fmt.Printf("nitrogen: wrote %s (%d path ops)\n", out, len(seen))
	fmt.Println("nitrogen: tip — serve live spec with app.OpenAPI(title, desc, version) after routes")
}

// describeResourceRoute documents a Resource CRUD route with the model's
// schemas and the conventional statuses (201 create, 204 delete).
func describeResourceRoute(info *openapi.RouteInfo, rs resourceSchemas) {
	item := strings.HasSuffix(info.Path, "/:id")
	switch {
	case info.Method == "GET" && !item:
		info.Summary = "List " + rs.full
		info.SuccessStatus = 200
		info.ResponseSchema = openapi.RefSchema(rs.list)
		for _, q := range []struct{ name, typ string }{{"page", "integer"}, {"per_page", "integer"}, {"sort", "string"}} {
			info.Params = append(info.Params, openapi.Parameter{Name: q.name, In: "query", Schema: &openapi.Schema{Type: q.typ}})
		}
	case info.Method == "GET":
		info.Summary = "Get " + rs.full
		info.SuccessStatus = 200
		info.ResponseSchema = openapi.RefSchema(rs.full)
	case info.Method == "POST":
		info.Summary = "Create " + rs.full
		info.SuccessStatus = 201
		info.RequestBody = openapi.JSONBody(openapi.RefSchema(rs.input), true, nil)
		info.ResponseSchema = openapi.RefSchema(rs.full)
	case info.Method == "PATCH":
		info.Summary = "Update " + rs.full
		info.SuccessStatus = 200
		info.RequestBody = openapi.JSONBody(openapi.RefSchema(rs.patch), true, nil)
		info.ResponseSchema = openapi.RefSchema(rs.full)
	case info.Method == "DELETE":
		info.Summary = "Delete " + rs.full
		info.SuccessStatus = 204
	}
}

func tagFromPath(path string) string {
	parts := strings.Split(strings.Trim(path, "/"), "/")
	if len(parts) == 0 || parts[0] == "" {
		return "default"
	}
	return parts[0]
}

func pathParams(path string) []openapi.Parameter {
	var out []openapi.Parameter
	for _, seg := range strings.Split(path, "/") {
		name := ""
		if strings.HasPrefix(seg, ":") {
			name = strings.TrimPrefix(seg, ":")
		} else if strings.HasPrefix(seg, "{") && strings.HasSuffix(seg, "}") {
			name = strings.TrimSuffix(strings.TrimPrefix(seg, "{"), "}")
		}
		if name == "" {
			continue
		}
		out = append(out, openapi.Parameter{
			Name:     name,
			In:       "path",
			Required: true,
			Schema:   &openapi.Schema{Type: "string"},
		})
	}
	return out
}

func looksProtected(path string) bool {
	p := strings.ToLower(path)
	return strings.Contains(p, "/profile") || strings.Contains(p, "/me") ||
		strings.Contains(p, "/admin") || strings.HasSuffix(p, "/:id")
}
