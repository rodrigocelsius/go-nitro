package main

import (
	"fmt"
	"go/format"
	"os"
	"path/filepath"
	"strings"

	blinqgen "github.com/rodrigocelsius/go-nitro/codegen/blinq/v2"
	datagen "github.com/rodrigocelsius/go-nitro/codegen/data/v2"
)

// dataOutPaths resolves where BLinq codegen writes files.
//
// Default (split layout):
//   - internal/model/product.go  → DSL internal/modelgen/product_gen.go (pkg modelgen)
//   - productmodel/product.go    → DSL productmodel/modelgen/product_gen.go (pkg modelgen)
//
// Resource CoC uses plural(struct) or an optional func (T) TableName() on the
// model — --data does not emit *_tablename_gen.go.
//
// --same-package keeps legacy colocated *_model_gen.go (DSL + TableName).
type dataOutPaths struct {
	SamePackage bool
	ModelPkg    string
	DSLPkg      string
	DSLPath     string
	StaleTable  string // leftover *_tablename_gen.go to delete
	LegacyPath  string // set when SamePackage
}

func resolveDataOut(inputPath string, samePackage bool) (dataOutPaths, error) {
	abs, err := filepath.Abs(inputPath)
	if err != nil {
		abs = inputPath
	}
	dir := filepath.Dir(abs)
	base := strings.TrimSuffix(filepath.Base(abs), ".go")
	modelPkg, err := blinqgen.ParsePackageName(inputPath)
	if err != nil {
		return dataOutPaths{}, err
	}

	if samePackage {
		return dataOutPaths{
			SamePackage: true,
			ModelPkg:    modelPkg,
			DSLPkg:      modelPkg,
			LegacyPath:  filepath.Join(dir, base+"_model_gen.go"),
		}, nil
	}

	dirBase := filepath.Base(dir)
	parent := filepath.Dir(dir)
	var dslDir, dslPkg string
	if dirBase == "model" {
		// Clean Arch: internal/model → internal/modelgen
		dslDir = filepath.Join(parent, "modelgen")
		dslPkg = "modelgen"
	} else {
		// Flat package (e.g. examples/.../productmodel): keep under same module root
		// productmodel/modelgen — import ".../productmodel/modelgen"
		dslDir = filepath.Join(dir, "modelgen")
		dslPkg = "modelgen"
	}

	return dataOutPaths{
		ModelPkg:   modelPkg,
		DSLPkg:     dslPkg,
		DSLPath:    filepath.Join(dslDir, base+"_gen.go"),
		StaleTable: filepath.Join(dir, base+"_tablename_gen.go"),
	}, nil
}

func cmdMakeData(inputPath string, samePackage bool) {
	if err := generateBlinqData(inputPath, samePackage); err != nil {
		fmt.Fprintf(os.Stderr, "nitrogen: %v\n", err)
		os.Exit(1)
	}
}

func generateBlinqData(inputPath string, samePackage bool) error {
	models, err := blinqgen.ParseModels(inputPath)
	if err != nil {
		return err
	}

	out, err := resolveDataOut(inputPath, samePackage)
	if err != nil {
		return err
	}

	if out.SamePackage {
		code, err := blinqgen.Generate(out.DSLPkg, "github.com/rodrigocelsius/go-nitro/blinq/v2/field", models)
		if err != nil {
			return err
		}
		if err := writeFormatted(out.LegacyPath, code); err != nil {
			return err
		}
		fmt.Printf("nitrogen: generated %s (BLinq, same-package)\n", out.LegacyPath)
		return nil
	}

	dsl, err := blinqgen.GenerateDSL(out.DSLPkg, "github.com/rodrigocelsius/go-nitro/blinq/v2/field", models)
	if err != nil {
		return err
	}
	if err := writeFormatted(out.DSLPath, dsl); err != nil {
		return err
	}
	fmt.Printf("nitrogen: generated %s (BLinq DSL, package %s)\n", out.DSLPath, out.DSLPkg)

	removeStaleTableNameFile(out.StaleTable)
	tipCustomTableName(models)

	legacy := strings.TrimSuffix(inputPath, ".go") + "_model_gen.go"
	if _, err := os.Stat(legacy); err == nil {
		_ = os.Remove(legacy)
		fmt.Printf("nitrogen: removed legacy %s\n", legacy)
	}
	return nil
}

func removeStaleTableNameFile(path string) {
	if path == "" {
		return
	}
	b, err := os.ReadFile(path)
	if err != nil {
		return
	}
	if !strings.Contains(string(b), "Code generated by nitro/codegen/blinq") {
		return
	}
	if err := os.Remove(path); err == nil {
		fmt.Printf("nitrogen: removed stale %s (Resource CoC / optional TableName on the model)\n", path)
	}
}

func tipCustomTableName(models []datagen.Model) {
	for _, m := range models {
		conv := datagen.TableNameFromStruct(m.StructName)
		if m.TableName == conv {
			continue
		}
		fmt.Printf("nitrogen: tip — %s table is %q (not convention %q); for app.Resource CoC add:\n\tfunc (%s) TableName() string { return %q }\n",
			m.StructName, m.TableName, conv, m.StructName, m.TableName)
	}
}

func writeFormatted(path, code string) error {
	formatted, err := format.Source([]byte(code))
	if err != nil {
		formatted = []byte(code)
	}
	return writeFile(path, string(formatted))
}
