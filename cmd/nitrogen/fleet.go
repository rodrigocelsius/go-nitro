package main

import (
	"fmt"
	"os"
	"path/filepath"
	"strings"
)

func cmdNewFleet(o newOpts) {
	if len(o.services) == 0 {
		o.services = []string{"gateway", "nfe"}
		fmt.Println("nitrogen: --fleet without --services; defaulting to gateway,nfe")
	}
	switch o.broker {
	case "":
		o.broker = "nats"
	case "nats", "rabbitmq":
	default:
		fmt.Fprintf(os.Stderr, "nitrogen: --broker %q: use nats or rabbitmq\n", o.broker)
		os.Exit(1)
	}
	root := o.name
	module := normalizeModulePath(o.module)
	if err := os.MkdirAll(root, 0755); err != nil {
		fmt.Fprintf(os.Stderr, "nitrogen: failed to create directory: %v\n", err)
		os.Exit(1)
	}

	var workLines []string
	workLines = append(workLines, "go 1.26.0", "", "use (")

	var composeSvcs strings.Builder
	composeSvcs.WriteString("# Generated by nitrogen new --fleet — local development only.\nservices:\n")
	composeSvcs.WriteString(brokerCompose(o.broker))
	composeSvcs.WriteString(`  postgres:
    image: postgres:16-alpine
    environment:
      POSTGRES_USER: postgres
      POSTGRES_PASSWORD: postgres
      POSTGRES_DB: app
    ports:
      - "127.0.0.1:5432:5432"
    volumes:
      - postgres_data:/var/lib/postgresql/data
  # Valkey (BSD-3) instead of Redis >= 7.4 (RSALv2/SSPLv1); same protocol.
  valkey:
    image: valkey/valkey:8-alpine
    ports:
      - "127.0.0.1:6379:6379"
`)

	var makeTargets strings.Builder
	makeTargets.WriteString(".PHONY: tidy build\n\ntidy:\n")
	httpPort := 8080
	healthPort := 8081

	for _, svc := range o.services {
		svc = strings.TrimSpace(svc)
		if err := validateProjectName(svc); err != nil {
			fmt.Fprintf(os.Stderr, "nitrogen: service %q: %v\n", svc, err)
			os.Exit(1)
		}
		svcDir := filepath.Join(root, "services", svc)
		svcModule := module + "/services/" + svc
		tier := "worker"
		if svc == "gateway" {
			tier = "microservice"
		}
		files := projectTemplates(svc, svcModule, tier)
		if tier == "worker" {
			env := workerEnvSkeleton(svc, o.broker)
			files[".env"], files[".env.example"] = env, env
		}
		// Avoid nested compose per service in fleet — root compose owns infra.
		delete(files, "docker-compose.yml")
		if err := writeProjectFiles(svcDir, files); err != nil {
			fmt.Fprintf(os.Stderr, "nitrogen: %v\n", err)
			os.Exit(1)
		}
		if err := appendNitroReplace(filepath.Join(svcDir, "go.mod"), o.nitroPath); err != nil {
			fmt.Fprintf(os.Stderr, "nitrogen: replace: %v\n", err)
		}
		workLines = append(workLines, "\t./services/"+svc)

		if tier == "microservice" {
			composeSvcs.WriteString(fmt.Sprintf(`  %s:
    build: ./services/%s
    ports:
      - "127.0.0.1:%d:8080"
    env_file:
      - ./services/%s/.env
    depends_on:
      - %s
      - postgres
      - valkey
    restart: unless-stopped
`, svc, svc, httpPort, svc, o.broker))
			makeTargets.WriteString(fmt.Sprintf("\tcd services/%s && go mod tidy\n", svc))
			httpPort++
		} else {
			composeSvcs.WriteString(fmt.Sprintf(`  %s:
    build: ./services/%s
    ports:
      - "127.0.0.1:%d:8081"
    env_file:
      - ./services/%s/.env
    depends_on:
      - %s
    restart: unless-stopped
`, svc, svc, healthPort, svc, o.broker))
			makeTargets.WriteString(fmt.Sprintf("\tcd services/%s && go mod tidy\n", svc))
			healthPort++
		}
	}

	workLines = append(workLines, "\t./pkg", ")")
	_ = os.MkdirAll(filepath.Join(root, "pkg"), 0755)
	_ = writeFileFmt(filepath.Join(root, "pkg", ".gitkeep"), nil, 0644)
	_ = writeFileFmt(filepath.Join(root, "pkg", "go.mod"), []byte("module "+module+"/pkg\n\ngo 1.26.0\n"), 0644)

	composeSvcs.WriteString("\nvolumes:\n  postgres_data:\n")
	if o.broker == "nats" {
		composeSvcs.WriteString("  nats_data:\n")
	}
	_ = writeFileFmt(filepath.Join(root, "docker-compose.yml"), []byte(composeSvcs.String()), 0644)
	_ = writeFileFmt(filepath.Join(root, "go.work"), []byte(strings.Join(workLines, "\n")+"\n"), 0644)

	makeTargets.WriteString("\nbuild:\n")
	for _, svc := range o.services {
		if svc == "gateway" {
			makeTargets.WriteString(fmt.Sprintf("\tcd services/%s && go build -trimpath -ldflags=\"-s -w\" -o ../../bin/%s ./cmd/server\n", svc, svc))
		} else {
			makeTargets.WriteString(fmt.Sprintf("\tcd services/%s && go build -trimpath -ldflags=\"-s -w\" -o ../../bin/%s-worker ./cmd/worker\n", svc, svc))
		}
	}
	_ = os.MkdirAll(filepath.Join(root, "bin"), 0755)
	_ = writeFileFmt(filepath.Join(root, "Makefile"), []byte(makeTargets.String()), 0644)
	_ = writeFileFmt(filepath.Join(root, "README.md"), []byte(fmt.Sprintf("# %s\n\nGenerated by `nitrogen new --fleet`.\n\n```bash\ndocker compose up -d %s postgres valkey\nmake tidy\nmake build\n```\n", root, o.broker)), 0644)
	_ = writeFileFmt(filepath.Join(root, ".gitignore"), []byte(readTemplate("gitignore.tmpl")+"\n"), 0644)

	fmt.Printf("nitrogen: fleet %s created (%d services)\n", root, len(o.services))
	initAiRules(root)
	fmt.Printf("  cd %s\n", root)
	fmt.Println("  docker compose up -d")
	fmt.Println("  make tidy && make build")
}

// brokerCompose is the compose service of the fleet's broker.
func brokerCompose(broker string) string {
	if broker == "rabbitmq" {
		return `  rabbitmq:
    image: rabbitmq:3.13-management-alpine
    ports:
      - "127.0.0.1:5672:5672"
      - "127.0.0.1:15672:15672"
`
	}
	return `  # NATS JetStream (Apache-2.0): workers read NATS_URL via nitro.QueueFromEnv.
  nats:
    image: nats:2.11-alpine
    command: ["-js", "-sd", "/data", "-m", "8222"]
    ports:
      - "127.0.0.1:4222:4222"
      - "127.0.0.1:8222:8222"
    volumes:
      - nats_data:/data
`
}
