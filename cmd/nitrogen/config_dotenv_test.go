package main

import (
	"os"
	"path/filepath"
	"strings"
	"testing"
)

// `go run ./cmd/server` must see .env through os.Getenv (sqladapter.OpenEnv),
// so every generated config.Load exports .env first.
func TestConfigTemplatesLoadDotEnv(t *testing.T) {
	for _, name := range []string{"ca_config.go.tmpl", "worker_config.go.tmpl"} {
		b, err := projectTemplateFS.ReadFile("templates/" + name)
		if err != nil {
			t.Fatal(err)
		}
		if !strings.Contains(string(b), "nitro.LoadDotEnv()") {
			t.Errorf("%s: config.Load does not export .env", name)
		}
	}
}

// install upgrades a config.go generated by older CLIs.
func TestInstallPatchesLegacyConfigLoad(t *testing.T) {
	dir := t.TempDir()
	cwd, _ := os.Getwd()
	t.Cleanup(func() { _ = os.Chdir(cwd) })
	if err := os.Chdir(dir); err != nil {
		t.Fatal(err)
	}
	legacy := "package config\n\nimport nitro \"github.com/rodrigocelsius/go-nitro/pkg/v2\"\n\ntype Config struct {\n\tPort int `env:\"PORT\" default:\"8080\"`\n}\n\nfunc Load() (Config, error) {\n\treturn nitro.ConfigOf[Config]()\n}\n"
	path := filepath.Join("internal", "config", "config.go")
	if err := os.MkdirAll(filepath.Dir(path), 0o755); err != nil {
		t.Fatal(err)
	}
	if err := os.WriteFile(path, []byte(legacy), 0o644); err != nil {
		t.Fatal(err)
	}
	for i := 0; i < 2; i++ { // second run: driver already present, still idempotent
		if err := patchConfigForDriver("sqlite"); err != nil {
			t.Fatal(err)
		}
	}
	b, _ := os.ReadFile(path)
	src := string(b)
	if strings.Count(src, "nitro.LoadDotEnv()") != 1 {
		t.Fatalf("want exactly one LoadDotEnv call:\n%s", src)
	}
	if !strings.Contains(src, "type DBConfig struct") {
		t.Fatalf("driver config missing:\n%s", src)
	}
}
