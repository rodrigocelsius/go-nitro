func TestGenerateBlinqData_NoTableNameFile(t *testing.T) {
	_, thisFile, _, _ := runtime.Caller(0)
	root := filepath.Dir(thisFile)
	base := filepath.Join(root, "testdata_nodtn")
	modelDir := filepath.Join(base, "model")
	input := filepath.Join(modelDir, "product.go")
	if err := os.MkdirAll(modelDir, 0755); err != nil {
		t.Fatal(err)
	}
	src := "package model\n\ntype Product struct {\n\tName string `json:\"name\" db:\"name\"`\n}\n"
	if err := os.WriteFile(input, []byte(src), 0644); err != nil {
		t.Fatal(err)
	}
	stale := filepath.Join(modelDir, "product_tablename_gen.go")
	if err := os.WriteFile(stale, []byte("// Code generated by nitro/codegen/blinq. DO NOT EDIT.\npackage model\n"), 0644); err != nil {
		t.Fatal(err)
	}
	t.Cleanup(func() { _ = os.RemoveAll(base) })

	if err := generateBlinqData(input, false); err != nil {
		t.Fatal(err)
	}
	if _, err := os.Stat(stale); !os.IsNotExist(err) {
		t.Fatalf("stale tablename file still present: %v", err)
	}
	dsl := filepath.Join(base, "modelgen", "product_gen.go")
	if _, err := os.Stat(dsl); err != nil {
		t.Fatalf("expected DSL %s: %v", dsl, err)
	}
}
