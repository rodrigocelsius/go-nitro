func TestResolveDataOut_ModelDir(t *testing.T) {
	_, thisFile, _, _ := runtime.Caller(0)
	root := filepath.Dir(thisFile)
	base := filepath.Join(root, "testdata_model")
	input := filepath.Join(base, "model", "product.go")
	if err := os.MkdirAll(filepath.Dir(input), 0755); err != nil {
		t.Fatal(err)
	}
	if err := os.WriteFile(input, []byte("package model\n\ntype Product struct{}\n"), 0644); err != nil {
		t.Fatal(err)
	}
	t.Cleanup(func() { _ = os.RemoveAll(base) })

	out, err := resolveDataOut(input, false)
	if err != nil {
		t.Fatal(err)
	}
	if out.DSLPkg != "modelgen" {
		t.Fatalf("DSLPkg=%q", out.DSLPkg)
	}
	if !strings.Contains(out.DSLPath, filepath.Join("modelgen", "product_gen.go")) {
		t.Fatalf("DSLPath=%q", out.DSLPath)
	}
	if !strings.HasSuffix(out.StaleTable, filepath.Join("model", "product_tablename_gen.go")) {
		t.Fatalf("StaleTable=%q", out.StaleTable)
	}
}

