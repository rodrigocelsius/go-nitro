// OTLPExporters builds the OTLP span and metric exporters. The protobuf/HTTP
// exporters weigh ~13 MB each in the binary, so they live in the
// adapters/otel/otlp package, which registers itself on import:
//
//	import _ "github.com/rodrigocelsius/go-nitro/adapters/otel/v2/otlp"
//
// Apps generated by nitrogen import it; a bare hello world does not.
type OTLPExporters struct {
	Trace  func(context.Context) (sdktrace.SpanExporter, error)
	Metric func(context.Context) (sdkmetric.Exporter, error)
}

var otlpExporters atomic.Pointer[OTLPExporters]

// RegisterOTLP installs the OTLP exporter constructors (called from the
// adapters/otel/otlp package init).
func RegisterOTLP(e OTLPExporters) { otlpExporters.Store(&e) }

// warnMissingOTLP is replaceable in tests.
var warnMissingOTLP = func() {
	fmt.Fprintln(os.Stderr, `nitro: warning: OTEL_EXPORTER_OTLP_ENDPOINT is set but the OTLP exporter is not linked — telemetry is NOT exported. Add: import _ "github.com/rodrigocelsius/go-nitro/adapters/otel/v2/otlp"`)
}

var (
	installOnce sync.Once
	installErr  error
	provider    *Provider

	sdkTP *sdktrace.TracerProvider
	sdkMP *sdkmetric.MeterProvider

	forceOff atomic.Bool
)

// ForceDisable desliga telemetria de forma permanente neste processo
// (Config.DisableTelemetry). Impede Ensure e pgx.Open de reinstalar OTel.
func ForceDisable() {
	forceOff.Store(true)
	domain.SetDefaultTracer(domain.NopTracer())
	domain.SetDefaultMeter(domain.NopMeter())
}

// Disabled reports whether telemetry was turned off by env / tests / ForceDisable.
// Opt-out: NITRO_OTEL=0|false|off, OTEL_SDK_DISABLED=true, ForceDisable().
// Em `go test`, fica off salvo NITRO_OTEL_IN_TESTS=1.
func Disabled() bool {
	if forceOff.Load() {
		return true
	}
	if testing.Testing() && os.Getenv("NITRO_OTEL_IN_TESTS") != "1" {
		return true
	}
	v := strings.ToLower(strings.TrimSpace(os.Getenv("NITRO_OTEL")))
	if v == "0" || v == "false" || v == "off" || v == "no" {
		return true
	}
	return strings.EqualFold(strings.TrimSpace(os.Getenv("OTEL_SDK_DISABLED")), "true")
}

// Ensure installs the OpenTelemetry SDK once and registers Tracer/Meter on domain.
// Safe to call from nitro.New and pgx.Open (idempotent).
//
// Export (never mixed with access log by default):
//   - OTEL_EXPORTER_OTLP_ENDPOINT (or *_TRACES/_METRICS) → OTLP HTTP (collector),
//     when adapters/otel/otlp is linked (a warning is printed otherwise)
//   - NITRO_OTEL_STDOUT=1 → stdout (debug only; avoid in production)
//   - otherwise → no-op tracer/meter: nothing would be exported, so no span is
//     recorded and requests pay no telemetry cost
//
// W3C trace context (traceparent/tracestate) and baggage are propagated
// whenever the SDK is installed.
//
// Opt-out: NITRO_OTEL=0, OTEL_SDK_DISABLED=true, ForceDisable / DisableTelemetry.
func Ensure(serviceName string) error {
	installOnce.Do(func() {
		if Disabled() {
			domain.SetDefaultTracer(domain.NopTracer())
			domain.SetDefaultMeter(domain.NopMeter())
			return
		}
		if serviceName == "" {
			serviceName = os.Getenv("OTEL_SERVICE_NAME")
		}
		if serviceName == "" {
			serviceName = "nitro"
		}
		if !hasExporter() {
			domain.SetDefaultTracer(domain.NopTracer())
			domain.SetDefaultMeter(domain.NopMeter())
			return
		}
		installErr = installSDK(serviceName)
		if installErr != nil {
			domain.SetDefaultTracer(domain.NopTracer())
			domain.SetDefaultMeter(domain.NopMeter())
			return
		}
		provider = NewProvider(serviceName)
		domain.SetDefaultTracer(provider.Tracer())
		domain.SetDefaultMeter(provider.Meter())
	})
	return installErr
}

// Active reports whether the SDK is installed (some exporter is configured).
// When false, HTTP tracing/metrics middleware can be skipped entirely.
func Active() bool {
	_ = Ensure("")
	return provider != nil
}

// DefaultProvider returns the Provider after Ensure (nil if disabled/failed).
func DefaultProvider() *Provider {
	_ = Ensure("")
	return provider
}

// ForceFlush sends pending spans/metrics (batch) to the exporter.
func ForceFlush(ctx context.Context) error {
	var first error
	if sdkTP != nil {
		if err := sdkTP.ForceFlush(ctx); err != nil && first == nil {
			first = err
		}
	}
	if sdkMP != nil {
		if err := sdkMP.ForceFlush(ctx); err != nil && first == nil {
			first = err
		}
	}
	return first
}

// Shutdown ForceFlushes then shuts down TracerProvider/MeterProvider.
// Safe to call multiple times; after Shutdown, defaults revert to nop.
func Shutdown(ctx context.Context) error {
	err := ForceFlush(ctx)
	if sdkTP != nil {
		if e := sdkTP.Shutdown(ctx); e != nil && err == nil {
			err = e
		}
		sdkTP = nil
	}
	if sdkMP != nil {
		if e := sdkMP.Shutdown(ctx); e != nil && err == nil {
			err = e
		}
		sdkMP = nil
	}
	domain.SetDefaultTracer(domain.NopTracer())
	domain.SetDefaultMeter(domain.NopMeter())
	provider = nil
	return err
}

func installSDK(serviceName string) error {
	ctx := context.Background()
	// Schemaless: resource.Default() carries the SDK's semconv schema URL, and
	// merging it with attributes built from another semconv version fails
	// ("conflicting Schema URL"), which silently disabled all export.
	res, err := resource.Merge(
		resource.Default(),
		resource.NewSchemaless(semconv.ServiceName(serviceName)),
	)
	if err != nil {
		return err
	}

	tp, err := newTracerProvider(ctx, res)
	if err != nil {
		return err
	}
	sdkTP = tp
	otel.SetTracerProvider(tp)
	otel.SetTextMapPropagator(propagation.NewCompositeTextMapPropagator(
		propagation.TraceContext{}, propagation.Baggage{}))

	mp, err := newMeterProvider(ctx, res)
	if err != nil {
		return err
	}
	sdkMP = mp
	otel.SetMeterProvider(mp)
	return nil
}

func otlpConfigured() bool {
	return os.Getenv("OTEL_EXPORTER_OTLP_ENDPOINT") != "" ||
		os.Getenv("OTEL_EXPORTER_OTLP_TRACES_ENDPOINT") != "" ||
		os.Getenv("OTEL_EXPORTER_OTLP_METRICS_ENDPOINT") != ""
}

// useOTLP reports whether OTLP export is configured and the exporter linked.
func useOTLP() bool {
	return otlpConfigured() && otlpExporters.Load() != nil
}

// hasExporter reports whether any span/metric destination is configured.
func hasExporter() bool {
	if otlpConfigured() && otlpExporters.Load() == nil {
		warnMissingOTLP()
	}
	return useOTLP() || useStdout()
}

func useStdout() bool {
	v := strings.ToLower(strings.TrimSpace(os.Getenv("NITRO_OTEL_STDOUT")))
	return v == "1" || v == "true" || v == "on" || v == "yes"
}

func newTracerProvider(ctx context.Context, res *resource.Resource) (*sdktrace.TracerProvider, error) {
	opts := []sdktrace.TracerProviderOption{sdktrace.WithResource(res)}
	switch {
	case useOTLP():
		exp, err := otlpExporters.Load().Trace(ctx)
		if err != nil {
			return nil, err
		}
		opts = append(opts, sdktrace.WithBatcher(exp))
	case useStdout():
		exp, err := stdouttrace.New(stdouttrace.WithPrettyPrint())
		if err != nil {
			return nil, err
		}
		opts = append(opts, sdktrace.WithBatcher(exp))
	}
	return sdktrace.NewTracerProvider(opts...), nil
}

func newMeterProvider(ctx context.Context, res *resource.Resource) (*sdkmetric.MeterProvider, error) {
	opts := []sdkmetric.Option{sdkmetric.WithResource(res)}
	switch {
	case useOTLP():
		exp, err := otlpExporters.Load().Metric(ctx)
		if err != nil {
			return nil, err
		}
		opts = append(opts, sdkmetric.WithReader(sdkmetric.NewPeriodicReader(exp)))
	case useStdout():
		exp, err := stdoutmetric.New()
		if err != nil {
			return nil, err
		}
		opts = append(opts, sdkmetric.WithReader(sdkmetric.NewPeriodicReader(exp)))
	}
	return sdkmetric.NewMeterProvider(opts...), nil
}
