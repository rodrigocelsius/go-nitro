package gen

import (
	"fmt"
	"strings"
)

// GenerateRoutes produces Go source for wrappers of every annotated
// route in routes. Each wrapper is named <FuncName>_NitroHandler with
// signature func(c *nitro.Ctx) error, compatible with nitro.Handler —
// the developer registers it like:
//
//	app.Get("/users/:id", handlers.GetUser_NitroHandler)
//
// packageName must match the package where the original functions live.
// nitroImportPath is the nitro package import path (usually
// "github.com/rodrigocelsius/go-nitro/v2").
func GenerateRoutes(packageName, nitroImportPath string, routes []RouteAnnotation) (string, error) {
	if len(routes) == 0 {
		return "", nil
	}

	var b strings.Builder
	fmt.Fprintf(&b, "// Code generated by nitro/json/gen. DO NOT EDIT.\n\n")
	fmt.Fprintf(&b, "package %s\n\n", packageName)
	fmt.Fprintf(&b, "import (\n\t\"strconv\"\n\n\tnitro %q\n)\n\n", nitroImportPath)

	for _, route := range routes {
		code, err := generateRouteWrapper(route)
		if err != nil {
			return "", fmt.Errorf("gen: route wrapper for %s: %w", route.FuncName, err)
		}
		b.WriteString(code)
		b.WriteString("\n")
	}

	return b.String(), nil
}

func generateRouteWrapper(route RouteAnnotation) (string, error) {
	var b strings.Builder
	fmt.Fprintf(&b, "func %s_NitroHandler(%s *nitro.Ctx) error {\n", route.FuncName, route.CtxParam)

	callArgs := []string{route.CtxParam}

	for _, p := range route.PathParams {
		code, err := extractParamCode(route.CtxParam, p)
		if err != nil {
			return "", err
		}
		b.WriteString(code)
		callArgs = append(callArgs, p.Name)
	}

	fmt.Fprintf(&b, "\treturn %s(%s)\n", route.FuncName, strings.Join(callArgs, ", "))
	b.WriteString("}\n")
	return b.String(), nil
}

// extractParamCode generates the snippet that extracts and converts a
// path parameter, assigning it to a Go variable of the same name.
// Always uses ":=" — Go allows that even when "err" was already
// declared by a previous parameter in the same scope, as long as at
// least one left-hand variable (the parameter itself, e.g. "itemId")
// is new. There is no need to track whether "err" was already declared.
func extractParamCode(ctxName string, p RouteParam) (string, error) {
	switch p.Kind {
	case KindString:
		return fmt.Sprintf("\t%s := %s.Param(%q)\n", p.Name, ctxName, p.Name), nil
	case KindInt:
		return fmt.Sprintf(
			"\t%sRaw := %s.Param(%q)\n\t%s, err := strconv.Atoi(%sRaw)\n\tif err != nil {\n\t\treturn err\n\t}\n",
			p.Name, ctxName, p.Name, p.Name, p.Name,
		), nil
	case KindFloat:
		return fmt.Sprintf(
			"\t%sRaw := %s.Param(%q)\n\t%s, err := strconv.ParseFloat(%sRaw, 64)\n\tif err != nil {\n\t\treturn err\n\t}\n",
			p.Name, ctxName, p.Name, p.Name, p.Name,
		), nil
	case KindBool:
		return fmt.Sprintf(
			"\t%sRaw := %s.Param(%q)\n\t%s, err := strconv.ParseBool(%sRaw)\n\tif err != nil {\n\t\treturn err\n\t}\n",
			p.Name, ctxName, p.Name, p.Name, p.Name,
		), nil
	default:
		return "", fmt.Errorf("unsupported param kind for %q", p.Name)
	}
}
