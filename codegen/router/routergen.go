// Package routergen implements Phase 6: build-time generation of a
// compiled router, eliminating the runtime radix tree for extreme
// production mode.
//
// BENCHMARK-VALIDATED DECISIONS (see router_compiled_proto):
//   - a direct switch on string (Go optimizes internally) beats a
//     hand-precomputed hash in EVERY scenario tested, with a growing
//     margin as path depth increases (~53% faster in the deepest case
//     tested).
//   - case order in the switch does not matter for performance (Go
//     uses binary search/jump table, not sequential comparison).
//   - Final result: compiled router is ~2x faster on a static route
//     and ~4.3x faster (with zero allocation) on a dynamic route,
//     compared to the Phase 2 runtime radix tree.
package routergen

import (
	"fmt"
	"sort"
	"strings"
)

// Route is the route input given to the generator: method, path, and
// handler name (must match a Go function reachable in the package
// where the code will be generated — see nitro.Route.Name).
type Route struct {
	Method      string
	Path        string
	HandlerName string
}

// segmentNode is a node of the intermediate decision tree used to
// build the nested switch. It is not the Phase 2 runtime radix tree —
// it is an auxiliary structure for codegen only, discarded after
// Generate() returns.
type segmentNode struct {
	name        string // static segment text, or param name
	isParam     bool
	handlerName string // non-empty if a route ends exactly here
	children    []*segmentNode
}

// Generate produces the full compiled-router Go source for the given
// routes, grouped by HTTP method.
func Generate(packageName, nitroImportPath string, routes []Route) (string, error) {
	byMethod := groupByMethod(routes)

	var b strings.Builder
	fmt.Fprintf(&b, "// Code generated by nitro/routergen. DO NOT EDIT.\n\n")
	fmt.Fprintf(&b, "package %s\n\n", packageName)
	fmt.Fprintf(&b, "import (\n\tnitro %q\n)\n\n", nitroImportPath)

	b.WriteString("// MatchCompiled resolves method+path directly via a nested switch,\n")
	b.WriteString("// with no runtime data structure (neither hash nor tree).\n")
	b.WriteString("// Generated from the App named routes at generation time.\n")
	b.WriteString("func MatchCompiled(c *nitro.Ctx, method string, path string) (nitro.Handler, bool) {\n")
	b.WriteString("\tswitch method {\n")

	methods := make([]string, 0, len(byMethod))
	for m := range byMethod {
		methods = append(methods, m)
	}
	sort.Strings(methods)

	for _, method := range methods {
		fmt.Fprintf(&b, "\tcase %q:\n", method)
		tree := buildTree(byMethod[method])
		code, err := generateMatchBody(tree, "\t\t")
		if err != nil {
			return "", fmt.Errorf("routergen: method %s: %w", method, err)
		}
		b.WriteString(code)
	}

	b.WriteString("\t}\n")
	b.WriteString("\treturn nil, false\n")
	b.WriteString("}\n")

	return b.String(), nil
}

func groupByMethod(routes []Route) map[string][]Route {
	m := make(map[string][]Route)
	for _, r := range routes {
		m[r.Method] = append(m[r.Method], r)
	}
	return m
}

// buildTree builds the intermediate decision tree from the routes of a
// single method.
func buildTree(routes []Route) *segmentNode {
	root := &segmentNode{}
	for _, r := range routes {
		node := root
		for _, seg := range splitPath(r.Path) {
			isParam := strings.HasPrefix(seg, ":")
			var found *segmentNode
			for _, child := range node.children {
				if child.isParam == isParam && child.name == seg {
					found = child
					break
				}
			}
			if found == nil {
				found = &segmentNode{name: seg, isParam: isParam}
				node.children = append(node.children, found)
			}
			node = found
		}
		node.handlerName = r.HandlerName
	}
	return root
}

func splitPath(path string) []string {
	var segs []string
	for _, s := range strings.Split(path, "/") {
		if s != "" {
			segs = append(segs, s)
		}
	}
	return segs
}
