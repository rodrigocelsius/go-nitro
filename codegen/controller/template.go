package controller

import (
	"fmt"
	"strings"
)

// GenerateController generates a Resource mount helper (Nitro v1 CoC).
func GenerateController(cfg ControllerConfig) string {
	var b strings.Builder

	fmt.Fprintf(&b, "// Code generated by nitrogen make --controller. DO NOT EDIT.\n\n")
	fmt.Fprintf(&b, "package %s\n\n", cfg.PackageName)
	b.WriteString("import (\n")
	b.WriteString("\tnitro \"github.com/rodrigocelsius/go-nitro/pkg/v2\"\n")
	b.WriteString(")\n\n")

	filterable := CollectFilterableJSONNames(cfg.Fields)
	sortable := CollectSortableJSONNames(cfg.Fields)

	fmt.Fprintf(&b, "// Mount%s registers CRUD routes for %s via app.Resource.\n", cfg.StructName, cfg.StructName)
	fmt.Fprintf(&b, "// Filters: %s\n", strings.Join(filterable, ", "))
	fmt.Fprintf(&b, "// Sort: ?sort=field or ?sort=-field (%s)\n", strings.Join(sortable, ", "))
	fmt.Fprintf(&b, "func Mount%s(app *nitro.App, repo nitro.ResourceRepository) {\n", cfg.StructName)
	fmt.Fprintf(&b, "\tapp.Resource(\"/%s\", &%s{}, repo, &nitro.ResourceConfig{\n", cfg.TableName, cfg.StructName)
	if len(filterable) > 0 {
		fmt.Fprintf(&b, "\t\tFilterable: []string{%s},\n", quoteJoin(filterable))
	}
	if len(sortable) > 0 {
		fmt.Fprintf(&b, "\t\tSortable:   []string{%s},\n", quoteJoin(sortable))
	}
	b.WriteString("\t})\n")
	b.WriteString("}\n")

	return b.String()
}

func quoteJoin(ss []string) string {
	parts := make([]string, len(ss))
	for i, s := range ss {
		parts[i] = fmt.Sprintf("%q", s)
	}
	return strings.Join(parts, ", ")
}

// GenerateControllerFilename generates the filename for the controller
func GenerateControllerFilename(structName string) string {
	return fmt.Sprintf("%s_resource_gen.go", strings.ToLower(structName))
}
