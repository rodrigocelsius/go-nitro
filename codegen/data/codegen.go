package datagen

import (
	"fmt"
	"strings"
)

// Generate produces Go source for the metamodel of the given models.
// For each Model, it generates a <StructName>Meta type and a
// <StructName>Model var with one field.Field[any] per column.
//
// fieldImportPath is the import path of the blinq/field package.
func Generate(packageName, fieldImportPath string, models []Model) (string, error) {
	if len(models) == 0 {
		return "", nil
	}
	if fieldImportPath == "" {
		fieldImportPath = "github.com/rodrigocelsius/go-nitro/blinq/v2/field"
	}

	var b strings.Builder
	fmt.Fprintf(&b, "// Code generated by nitro/data/gen. DO NOT EDIT.\n\n")
	fmt.Fprintf(&b, "package %s\n\n", packageName)
	fmt.Fprintf(&b, "import (\n\tblinqfield %q\n)\n\n", fieldImportPath)

	for _, m := range models {
		code, err := generateModelVar(m)
		if err != nil {
			return "", fmt.Errorf("datagen: model %s: %w", m.StructName, err)
		}
		b.WriteString(code)
		b.WriteString("\n")
	}

	return b.String(), nil
}

func generateModelVar(m Model) (string, error) {
	var b strings.Builder

	metaTypeName := m.StructName + "Meta"
	fmt.Fprintf(&b, "type %s struct {\n", metaTypeName)
	b.WriteString("\tTable string\n")
	for _, c := range m.Columns {
		fmt.Fprintf(&b, "\t%s blinqfield.Field[any]\n", c.GoName)
	}
	b.WriteString("}\n\n")

	varName := m.StructName + "Model"
	fmt.Fprintf(&b, "var %s = %s{\n", varName, metaTypeName)
	fmt.Fprintf(&b, "\tTable: %q,\n", m.TableName)
	for _, c := range m.Columns {
		fmt.Fprintf(&b, "\t%s: blinqfield.Field[any]{Table: %q, Column: %q},\n", c.GoName, m.TableName, c.ColumnName)
	}
	b.WriteString("}\n")

	return b.String(), nil
}
