package blinqgen

import (
	"fmt"
	"strings"

	nitroast "github.com/rodrigocelsius/go-nitro/codegen/ast/v2"
	datagen "github.com/rodrigocelsius/go-nitro/codegen/data/v2"
)

// Options controls what Generate emits.
type Options struct {
	// SkipTableName omits func (T) TableName() — use when TableName lives in the model package.
	SkipTableName bool
}

// Generate produces a typed BLinq metamodel: Entity + Field[T] per column (+ TableName by default).
//
// fieldImportPath default: github.com/rodrigocelsius/go-nitro/blinq/v2/field
func Generate(packageName, fieldImportPath string, models []datagen.Model) (string, error) {
	return GenerateWithOptions(packageName, fieldImportPath, models, Options{})
}

// GenerateDSL is Generate with SkipTableName (for package modelgen).
func GenerateDSL(packageName, fieldImportPath string, models []datagen.Model) (string, error) {
	return GenerateWithOptions(packageName, fieldImportPath, models, Options{SkipTableName: true})
}

// GenerateTableNames emits only TableName() methods for the model package.
func GenerateTableNames(packageName string, models []datagen.Model) (string, error) {
	if len(models) == 0 {
		return "", nil
	}
	var b strings.Builder
	fmt.Fprintf(&b, "// Code generated by nitro/codegen/blinq. DO NOT EDIT.\n\n")
	fmt.Fprintf(&b, "package %s\n\n", packageName)
	for _, m := range models {
		fmt.Fprintf(&b, "// TableName returns the DB/resource table for %s (from //nitro:table= or convention).\n", m.StructName)
		fmt.Fprintf(&b, "func (%s) TableName() string { return %q }\n\n", m.StructName, m.TableName)
	}
	return b.String(), nil
}

// GenerateWithOptions produces a typed BLinq metamodel.
func GenerateWithOptions(packageName, fieldImportPath string, models []datagen.Model, opts Options) (string, error) {
	if len(models) == 0 {
		return "", nil
	}
	if fieldImportPath == "" {
		fieldImportPath = "github.com/rodrigocelsius/go-nitro/blinq/v2/field"
	}

	needTime := false
	for _, m := range models {
		for _, c := range m.Columns {
			if strings.Contains(fieldGoType(c), "time.Time") {
				needTime = true
				break
			}
		}
	}

	var b strings.Builder
	fmt.Fprintf(&b, "// Code generated by nitro/codegen/blinq. DO NOT EDIT.\n\n")
	fmt.Fprintf(&b, "package %s\n\n", packageName)
	b.WriteString("import (\n")
	if needTime {
		b.WriteString("\t\"time\"\n\n")
	}
	fmt.Fprintf(&b, "\tblinqfield %q\n)\n\n", fieldImportPath)

	for _, m := range models {
		code, err := generateModel(m, opts)
		if err != nil {
			return "", fmt.Errorf("blinqgen: model %s: %w", m.StructName, err)
		}
		b.WriteString(code)
		b.WriteString("\n")
	}
	return b.String(), nil
}

// ParseModels delegates to codegen/data.
func ParseModels(filename string) ([]datagen.Model, error) {
	return datagen.ParseModels(filename)
}

// ParsePackageName delegates to codegen/data.
func ParsePackageName(filename string) (string, error) {
	return datagen.ParsePackageName(filename)
}

func generateModel(m datagen.Model, opts Options) (string, error) {
	softCol, tenantCol := softAndTenant(m)

	var b strings.Builder
	entityName := m.StructName + "Entity"
	fmt.Fprintf(&b, "// %s is metadata for table %q.\n", entityName, m.TableName)
	fmt.Fprintf(&b, "var %s = blinqfield.Entity{\n", entityName)
	fmt.Fprintf(&b, "\tName: %q,\n", m.TableName)
	if softCol != "" {
		fmt.Fprintf(&b, "\tSoftColumn: %q,\n", softCol)
	}
	if tenantCol != "" {
		fmt.Fprintf(&b, "\tTenantColumn: %q,\n", tenantCol)
	}
	b.WriteString("}\n\n")

	metaType := m.StructName + "Meta"
	fmt.Fprintf(&b, "type %s struct {\n", metaType)
	b.WriteString("\tTable string\n")
	for _, c := range m.Columns {
		goType := fieldGoType(c)
		fmt.Fprintf(&b, "\t%s blinqfield.Field[%s]\n", c.GoName, goType)
	}
	b.WriteString("}\n\n")

	fmt.Fprintf(&b, "var %sModel = %s{\n", m.StructName, metaType)
	fmt.Fprintf(&b, "\tTable: %q,\n", m.TableName)
	for _, c := range m.Columns {
		goType := fieldGoType(c)
		fmt.Fprintf(&b, "\t%s: blinqfield.Field[%s]{Table: %q, Column: %q},\n",
			c.GoName, goType, m.TableName, c.ColumnName)
	}
	b.WriteString("}\n")

	// Short DSL alias: Products.Active.Eq(true) instead of ProductModel.Active…
	short := shortMetaName(m)
	if short != "" && short != m.StructName+"Model" {
		fmt.Fprintf(&b, "\n// %s is a short alias of %sModel for the DSL.\nvar %s = %sModel\n", short, m.StructName, short, m.StructName)
	}

	if !opts.SkipTableName {
		fmt.Fprintf(&b, "\n// TableName returns the DB/resource table for %s (from //nitro:table= or convention).\n", m.StructName)
		fmt.Fprintf(&b, "func (%s) TableName() string { return %q }\n", m.StructName, m.TableName)
	}
	return b.String(), nil
}

// shortMetaName: table "products" → "Products"; avoid colliding with struct Product.
func shortMetaName(m datagen.Model) string {
	t := strings.TrimSpace(m.TableName)
	if t == "" {
		return ""
	}
	parts := strings.Split(t, "_")
	for i, p := range parts {
		if p == "" {
			continue
		}
		parts[i] = strings.ToUpper(p[:1]) + p[1:]
	}
	name := strings.Join(parts, "")
	if name == m.StructName {
		name += "s"
		if name == m.StructName {
			return ""
		}
	}
	return name
}

func softAndTenant(m datagen.Model) (softCol, tenantCol string) {
	for _, c := range m.Columns {
		tag := ""
		if c.Tags != nil {
			tag = c.Tags["blinq"]
		}
		if c.ColumnName == "deleted_at" || c.GoName == "DeletedAt" || hasTagToken(tag, "soft") {
			softCol = c.ColumnName
		}
		if hasTagToken(tag, "tenant") || c.ColumnName == "tenant_id" {
			tenantCol = c.ColumnName
		}
	}
	return softCol, tenantCol
}

func hasTagToken(tag, want string) bool {
	for _, p := range strings.Split(tag, ",") {
		if strings.TrimSpace(p) == want {
			return true
		}
	}
	return false
}

func fieldGoType(c datagen.Column) string {
	tn := strings.TrimSpace(c.TypeName)
	if tn != "" {
		return mapPortableType(tn)
	}
	switch c.Kind {
	case nitroast.KindString:
		return "string"
	case nitroast.KindInt:
		return "int"
	case nitroast.KindFloat:
		return "float64"
	case nitroast.KindBool:
		return "bool"
	case nitroast.KindTime:
		return "time.Time"
	default:
		return "any"
	}
}

func mapPortableType(tn string) string {
	ptr := strings.HasPrefix(tn, "*")
	base := strings.TrimPrefix(tn, "*")
	if i := strings.LastIndexByte(base, '.'); i >= 0 {
		base = base[i+1:]
	}
	var out string
	switch base {
	case "UUID":
		out = "string"
	case "DateTime", "Date", "TimeOfDay":
		out = "time.Time"
	case "Money", "Measure", "Decimal":
		out = "float64"
	default:
		out = strings.TrimPrefix(tn, "*")
	}
	if ptr {
		return "*" + out
	}
	return out
}
