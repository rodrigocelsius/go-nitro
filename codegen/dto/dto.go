// Package dto generates public DTOs from nitro:"public" tags / //nitro:public.
package dto

import (
	"fmt"
	"strings"

	nitroast "github.com/rodrigocelsius/go-nitro/codegen/ast/v2"
)

// GenerateFromFile reads models.go and generates *_public_gen.go.
func GenerateFromFile(filename, packageName string) (string, error) {
	defs, err := nitroast.ParseFile(filename)
	if err != nil {
		return "", err
	}
	ann, err := parsePublicStructs(filename)
	if err != nil {
		return "", err
	}
	return Generate(packageName, defs, ann)
}

// Generate produces Go code with {Type}Public + ToPublic.
func Generate(packageName string, defs []nitroast.StructDef, publicStructs map[string]bool) (string, error) {
	var b strings.Builder
	b.WriteString("// Code generated by nitrogen make:dto. DO NOT EDIT.\n\n")
	b.WriteString("package " + packageName + "\n\n")

	n := 0
	for _, def := range defs {
		fields := publicFields(def, publicStructs[def.Name])
		if len(fields) == 0 {
			continue
		}
		n++
		pubName := def.Name + "Public"
		b.WriteString(fmt.Sprintf("// %s is the public projection of %s.\n", pubName, def.Name))
		b.WriteString(fmt.Sprintf("type %s struct {\n", pubName))
		for _, f := range fields {
			jsonTag := f.Tags["json"]
			if jsonTag == "" {
				jsonTag = strings.ToLower(f.GoName)
			}
			b.WriteString(fmt.Sprintf("\t%s %s `json:%q`\n", f.GoName, f.TypeName, jsonTag))
		}
		b.WriteString("}\n\n")
		b.WriteString(fmt.Sprintf("// ToPublic maps %s → %s.\n", def.Name, pubName))
		b.WriteString(fmt.Sprintf("func (m %s) ToPublic() %s {\n", def.Name, pubName))
		b.WriteString(fmt.Sprintf("\treturn %s{\n", pubName))
		for _, f := range fields {
			b.WriteString(fmt.Sprintf("\t\t%s: m.%s,\n", f.GoName, f.GoName))
		}
		b.WriteString("\t}\n}\n\n")
		b.WriteString(fmt.Sprintf("// ToPublicSlice maps []%s → []%s.\n", def.Name, pubName))
		b.WriteString(fmt.Sprintf("func ToPublic%sSlice(in []%s) []%s {\n", def.Name, def.Name, pubName))
		b.WriteString(fmt.Sprintf("\tout := make([]%s, len(in))\n", pubName))
		b.WriteString("\tfor i := range in {\n")
		b.WriteString("\t\tout[i] = in[i].ToPublic()\n")
		b.WriteString("\t}\n\treturn out\n}\n\n")
	}
	if n == 0 {
		return "", fmt.Errorf("dto: no public fields found (use nitro:\"public\" or //nitro:public)")
	}
	return b.String(), nil
}

func publicFields(def nitroast.StructDef, allPublic bool) []nitroast.Field {
	var out []nitroast.Field
	for _, f := range def.Fields {
		if f.GoName == "" || !isExported(f.GoName) {
			continue
		}
		nitroTag := f.Tags["nitro"]
		if hasToken(nitroTag, "-") {
			continue
		}
		jsonTag := f.Tags["json"]
		if jsonTag == "-" {
			continue
		}
		if allPublic || hasToken(nitroTag, "public") {
			out = append(out, f)
		}
	}
	return out
}

func isExported(name string) bool {
	if name == "" {
		return false
	}
	r := name[0]
	return r >= 'A' && r <= 'Z'
}

func hasToken(tag, want string) bool {
	for _, p := range strings.Split(tag, ",") {
		if strings.TrimSpace(p) == want {
			return true
		}
	}
	return false
}
