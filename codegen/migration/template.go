package migration

import (
	"fmt"
	"os"
	"path/filepath"
	"strconv"
	"strings"
	"time"
)

// GenerateMigrationFile generates a complete SQL migration file content (goose).
func GenerateMigrationFile(migrationName string, tables []TableSchema) string {
	var b strings.Builder

	fmt.Fprintf(&b, "-- Migration: %s\n", migrationName)
	fmt.Fprintf(&b, "-- Generated by nitrogen migrate:make\n\n")

	fmt.Fprintln(&b, "-- +goose Up")
	fmt.Fprintln(&b)
	if CurrentDialect() == DialectPostgres {
		fmt.Fprintln(&b, `CREATE EXTENSION IF NOT EXISTS "pgcrypto";`)
		fmt.Fprintln(&b)
	}
	for _, table := range tables {
		b.WriteString(generateCreateTableSQL(table))
		b.WriteString("\n\n")
	}

	fmt.Fprintln(&b, "-- +goose Down")
	fmt.Fprintln(&b)
	for i := len(tables) - 1; i >= 0; i-- {
		fmt.Fprintf(&b, "DROP TABLE IF EXISTS %s;\n", tables[i].Name)
	}

	return b.String()
}

// generateCreateTableSQL generates a CREATE TABLE statement with indexes
func generateCreateTableSQL(schema TableSchema) string {
	var lines []string

	lines = append(lines, fmt.Sprintf("CREATE TABLE IF NOT EXISTS %s (", schema.Name))

	for i, col := range schema.Columns {
		line := generateColumnSQL(col)
		if i < len(schema.Columns)-1 {
			line += ","
		}
		lines = append(lines, line)
	}

	lines = append(lines, ");")

	for _, idx := range schema.Indexes {
		lines = append(lines, "")
		lines = append(lines, generateIndexSQL(idx, schema.Name))
	}

	return strings.Join(lines, "\n")
}

// generateColumnSQL generates SQL for a single column
func generateColumnSQL(col ColumnSchema) string {
	var parts []string
	parts = append(parts, fmt.Sprintf("    %-20s", col.Name))
	parts = append(parts, string(col.Type))

	if col.PrimaryKey {
		parts = append(parts, "PRIMARY KEY")
	}

	// BIGSERIAL already implies NOT NULL
	if col.NotNull && col.Type != TypeBigSerial {
		parts = append(parts, "NOT NULL")
	}

	if col.Unique && !col.PrimaryKey {
		parts = append(parts, "UNIQUE")
	}

	if col.Default != "" {
		parts = append(parts, fmt.Sprintf("DEFAULT %s", col.Default))
	}

	return strings.Join(parts, " ")
}

// generateIndexSQL generates SQL for an index (dialect-aware).
func generateIndexSQL(idx IndexSchema, tableName string) string {
	using := ""
	if idx.Using != "" && CurrentDialect() == DialectPostgres {
		using = " USING " + strings.ToUpper(idx.Using)
	}
	cols := strings.Join(idx.Columns, ", ")
	unique := ""
	if idx.Unique {
		unique = "UNIQUE "
	}
	where := ""
	// Partial indexes: Postgres + SQLite only (MySQL/MSSQL lack WHERE on CREATE INDEX).
	if idx.Where != "" {
		switch CurrentDialect() {
		case DialectPostgres, DialectSQLite:
			where = " WHERE " + idx.Where
		}
	}
	switch CurrentDialect() {
	case DialectSQLServer:
		// SQL Server has no CREATE INDEX IF NOT EXISTS.
		return fmt.Sprintf(`IF NOT EXISTS (SELECT 1 FROM sys.indexes WHERE name = N'%s' AND object_id = OBJECT_ID(N'%s'))
CREATE %sINDEX %s ON %s (%s)%s;`,
			idx.Name, tableName, unique, idx.Name, tableName, cols, where)
	case DialectMySQL:
		// MySQL 8+: IF NOT EXISTS; no partial WHERE.
		return fmt.Sprintf("CREATE %sINDEX IF NOT EXISTS %s ON %s (%s);",
			unique, idx.Name, tableName, cols)
	default:
		return fmt.Sprintf("CREATE %sINDEX IF NOT EXISTS %s ON %s%s (%s)%s;",
			unique, idx.Name, tableName, using, cols, where)
	}
}

// GenerateMigrationFilename generates NNNNNNNNNNNNNN_name.sql (goose timestamp).
func GenerateMigrationFilename(name string) string {
	ts := time.Now().UTC().Format("20060102150405")
	return fmt.Sprintf("%s_%s.sql", ts, sanitizeName(name))
}

// NextMigrationVersion returns the goose version for a new file in dir: the
// current UTC timestamp, bumped past the highest existing version so that
// migrations generated within the same second (scripts, agents) never share a
// version — a duplicate makes MigrateUp fail on the schema table's primary key.
func NextMigrationVersion(dir string) string {
	next, _ := strconv.ParseInt(time.Now().UTC().Format("20060102150405"), 10, 64)
	entries, _ := os.ReadDir(dir)
	for _, e := range entries {
		n := e.Name()
		if e.IsDir() || !strings.HasSuffix(n, ".sql") {
			continue
		}
		i := strings.IndexByte(n, '_')
		if i <= 0 {
			continue
		}
		if v, err := strconv.ParseInt(n[:i], 10, 64); err == nil && v >= next {
			next = v + 1
		}
	}
	return strconv.FormatInt(next, 10)
}

func sanitizeName(name string) string {
	name = strings.TrimSpace(strings.ToLower(name))
	name = strings.ReplaceAll(name, " ", "_")
	name = strings.ReplaceAll(name, "-", "_")
	var b strings.Builder
	for _, r := range name {
		if (r >= 'a' && r <= 'z') || (r >= '0' && r <= '9') || r == '_' {
			b.WriteRune(r)
		}
	}
	out := b.String()
	if out == "" {
		return "migration"
	}
	return out
}

// MakeOptions configures Write / Make.
type MakeOptions struct {
	Dir  string // default "migrations"
	Name string // default create_<tables>
}

// Make reads models.go, generates goose SQL, and writes it under Dir.
// Returns the path of the created file.
func Make(modelPath string, opts MakeOptions) (string, error) {
	_, tables, err := GenerateMigrationWithSchema(modelPath)
	if err != nil {
		return "", err
	}
	name := opts.Name
	if name == "" {
		name = defaultMigrationName(tables)
	}
	dir := opts.Dir
	if dir == "" {
		dir = "migrations"
	}
	return Write(dir, name, tables)
}

// Write writes the goose file into dir and returns the path.
// If a migration with the same logical name (create_<table>) already exists, it
// returns that path without writing a duplicate.
func Write(dir, name string, tables []TableSchema) (string, error) {
	if err := os.MkdirAll(dir, 0755); err != nil {
		return "", fmt.Errorf("migration: mkdir %s: %w", dir, err)
	}
	if existing := findMigrationByLogicalName(dir, name); existing != "" {
		return existing, nil
	}
	filename := fmt.Sprintf("%s_%s.sql", NextMigrationVersion(dir), sanitizeName(name))
	path := filepath.Join(dir, filename)
	content := GenerateMigrationFile(name, tables)
	if err := os.WriteFile(path, []byte(content), 0644); err != nil {
		return "", fmt.Errorf("migration: write %s: %w", path, err)
	}
	return path, nil
}

func findMigrationByLogicalName(dir, name string) string {
	entries, err := os.ReadDir(dir)
	if err != nil {
		return ""
	}
	suffix := "_" + name + ".sql"
	for _, e := range entries {
		if e.IsDir() {
			continue
		}
		n := e.Name()
		if strings.HasSuffix(n, suffix) {
			return filepath.Join(dir, n)
		}
	}
	return ""
}

func defaultMigrationName(tables []TableSchema) string {
	if len(tables) == 1 {
		return "create_" + tables[0].Name
	}
	if len(tables) == 0 {
		return "migration"
	}
	names := make([]string, 0, len(tables))
	for _, t := range tables {
		names = append(names, t.Name)
	}
	return "create_" + strings.Join(names, "_")
}
