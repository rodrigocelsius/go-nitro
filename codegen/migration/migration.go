package migration

import (
	"fmt"
	"strings"

	nitroast "github.com/rodrigocelsius/go-nitro/codegen/ast/v2"
	datagen "github.com/rodrigocelsius/go-nitro/codegen/data/v2"
)

// GenerateMigration creates a SQL migration from a Go model file
func GenerateMigration(filename string) (*Migration, error) {
	models, err := datagen.ParseModels(filename)
	if err != nil {
		return nil, fmt.Errorf("failed to parse models: %w", err)
	}

	if len(models) == 0 {
		return nil, fmt.Errorf("no models found in %s", filename)
	}

	var upStatements, downStatements []string

	for _, model := range models {
		schema := modelToSchema(model)
		up := generateCreateTable(schema)
		down := fmt.Sprintf("DROP TABLE IF EXISTS %s;", schema.Name)
		upStatements = append(upStatements, up)
		downStatements = append(downStatements, down)
	}

	return &Migration{
		Up:   strings.Join(upStatements, "\n\n"),
		Down: strings.Join(downStatements, "\n"),
	}, nil
}

// GenerateMigrationWithSchema creates a SQL migration and returns the table schemas
func GenerateMigrationWithSchema(filename string) (*Migration, []TableSchema, error) {
	models, err := datagen.ParseModels(filename)
	if err != nil {
		return nil, nil, fmt.Errorf("failed to parse models: %w", err)
	}

	if len(models) == 0 {
		return nil, nil, fmt.Errorf("no models found in %s", filename)
	}

	var upStatements, downStatements []string
	var tables []TableSchema

	for _, model := range models {
		schema := modelToSchema(model)
		up := generateCreateTable(schema)
		down := fmt.Sprintf("DROP TABLE IF EXISTS %s;", schema.Name)
		upStatements = append(upStatements, up)
		downStatements = append(downStatements, down)
		tables = append(tables, schema)
	}

	return &Migration{
		Up:   strings.Join(upStatements, "\n\n"),
		Down: strings.Join(downStatements, "\n"),
	}, tables, nil
}

// modelToSchema converts a datagen.Model to a TableSchema
func modelToSchema(model datagen.Model) TableSchema {
	schema := TableSchema{
		Name: model.TableName,
	}

	for _, col := range model.Columns {
		// Money / Measure expand to two physical columns.
		if base := portableTypeBase(col.TypeName); base == "Money" {
			schema.Columns = append(schema.Columns,
				ColumnSchema{Name: col.ColumnName + "_amount", Type: TypeBigInt, NotNull: !isNullable(col)},
				ColumnSchema{Name: col.ColumnName + "_currency", Type: TypeChar3, NotNull: !isNullable(col)},
			)
			continue
		}
		if base := portableTypeBase(col.TypeName); base == "Measure" {
			schema.Columns = append(schema.Columns,
				ColumnSchema{Name: col.ColumnName + "_value", Type: sqlDouble(), NotNull: !isNullable(col)},
				ColumnSchema{Name: col.ColumnName + "_unit", Type: TypeVarchar16, NotNull: !isNullable(col)},
			)
			continue
		}
		if base := portableTypeBase(col.TypeName); base == "LatLng" {
			schema.Columns = append(schema.Columns,
				ColumnSchema{Name: col.ColumnName + "_lat", Type: sqlGeoCoord(), NotNull: !isNullable(col)},
				ColumnSchema{Name: col.ColumnName + "_lng", Type: sqlGeoCoord(), NotNull: !isNullable(col)},
			)
			continue
		}

		colType := goTypeToSQL(col.Kind, col.TypeName)
		if isJSONColumn(col.Kind, col.TypeName, col.Tags) {
			colType = sqlJSON()
		}
		schemaCol := ColumnSchema{
			Name:    col.ColumnName,
			Type:    colType,
			NotNull: !isNullable(col),
		}

		// Process tags
		blinq := parseBlinqTokens("")
		if col.Tags != nil {
			blinq = parseBlinqTokens(col.Tags["blinq"])
		}

		if tagTruthy(col.Tags, "primary") || blinq["pk"] || blinq["primary"] {
			schemaCol.PrimaryKey = true
			schemaCol.NotNull = true
			if col.Kind == nitroast.KindInt {
				schemaCol.Type = TypeBigSerial
				schemaCol.Default = ""
			}
		}

		if tagTruthy(col.Tags, "unique") || blinq["unique"] {
			// Partial unique (where=…) uses index only — not column UNIQUE constraint.
			if blinqWhere(col.Tags) == "" {
				schemaCol.Unique = true
			}
		}

		if col.Tags != nil {
			if defaultVal, ok := col.Tags["default"]; ok && defaultVal != "" {
				schemaCol.Default = formatDefault(defaultVal, col.Kind)
			}
		}

		// Primary key for ID field (if not set by tag)
		if col.ColumnName == "id" && !schemaCol.PrimaryKey {
			schemaCol.PrimaryKey = true
			schemaCol.NotNull = true
			if col.Kind == nitroast.KindInt {
				schemaCol.Type = TypeBigSerial
			}
		}

		// string/UUID id → UUID (Nitro default: UUID v7 generated by the app via AutoID)
		if col.ColumnName == "id" && (col.Kind == nitroast.KindString || portableTypeBase(col.TypeName) == "UUID") {
			schemaCol.Type = sqlUUID()
			schemaCol.NotNull = true
			schemaCol.PrimaryKey = true
		}

		// int PK → BIGSERIAL (auto-increment), even if marked only with primary:"true"
		if schemaCol.PrimaryKey && col.Kind == nitroast.KindInt && schemaCol.Type == TypeBigInt {
			schemaCol.Type = TypeBigSerial
		}

		// Set defaults based on column name (if not set by tag).
		// id string/UUID: no DEFAULT — the app fills UUID v7 (AutoID).
		if schemaCol.Default == "" {
			switch {
			case col.ColumnName == "created_at" || col.ColumnName == "updated_at":
				schemaCol.Default = sqlNow()
			case col.ColumnName == "deleted_at":
				schemaCol.Nullable = true
				schemaCol.NotNull = false
			case isJSONType(schemaCol.Type) && isJSONArrayType(col.Kind, col.TypeName):
				schemaCol.Default = sqlEmptyJSONArray()
			}
		}

		schema.Columns = append(schema.Columns, schemaCol)
	}

	// Add indexes for common patterns + tags blinq:"index" / unique
	seenIdx := map[string]bool{}
	addIdx := func(idx IndexSchema) {
		key := idx.Name
		if seenIdx[key] {
			return
		}
		seenIdx[key] = true
		schema.Indexes = append(schema.Indexes, idx)
	}

	for _, col := range model.Columns {
		if col.ColumnName == "deleted_at" {
			addIdx(IndexSchema{
				Name:    fmt.Sprintf("idx_%s_deleted_at", model.TableName),
				Columns: []string{"deleted_at"},
				Where:   "deleted_at IS NULL",
			})
		}

		blinq := parseBlinqTokens("")
		if col.Tags != nil {
			blinq = parseBlinqTokens(col.Tags["blinq"])
		}
		wantIndex := blinq["index"] || tagTruthy(col.Tags, "index")
		wantUnique := blinq["unique"] || tagTruthy(col.Tags, "unique")
		isPK := col.ColumnName == "id" || blinq["pk"] || blinq["primary"] || tagTruthy(col.Tags, "primary")

		// PK is already an index — do not duplicate CREATE INDEX on id
		if isPK {
			continue
		}

		if wantUnique {
			idx := IndexSchema{
				Name:    fmt.Sprintf("idx_%s_%s_unique", model.TableName, col.ColumnName),
				Columns: []string{col.ColumnName},
				Unique:  true,
			}
			if w := blinqWhere(col.Tags); w != "" {
				idx.Where = w
			}
			addIdx(idx)
			continue
		}
		if blinq["gin"] {
			addIdx(IndexSchema{
				Name:    fmt.Sprintf("idx_%s_%s_gin", model.TableName, col.ColumnName),
				Columns: []string{col.ColumnName},
				Using:   "GIN",
			})
			continue
		}
		if wantIndex {
			addIdx(IndexSchema{
				Name:    fmt.Sprintf("idx_%s_%s", model.TableName, col.ColumnName),
				Columns: []string{col.ColumnName},
			})
		}
	}

	return schema
}

// parseBlinqTokens parses `blinq:"unique,index,pk,soft,tenant,gin,where=…"`.
// Tokens with `=` (e.g. where=) mark the key (where) as true; the value lives in blinqWhere.
func parseBlinqTokens(tag string) map[string]bool {
	out := map[string]bool{}
	for _, p := range strings.Split(tag, ",") {
		p = strings.TrimSpace(p)
		if p == "" {
			continue
		}
		key := p
		if i := strings.IndexByte(p, '='); i >= 0 {
			key = p[:i]
		}
		out[strings.ToLower(strings.TrimSpace(key))] = true
	}
	return out
}

// blinqWhere extracts the condition from `blinq:"…,where=deleted_at IS NULL"`.
func blinqWhere(tags map[string]string) string {
	if tags == nil {
		return ""
	}
	tag := tags["blinq"]
	for _, p := range strings.Split(tag, ",") {
		p = strings.TrimSpace(p)
		if len(p) >= 6 && strings.EqualFold(p[:6], "where=") {
			return strings.TrimSpace(p[6:])
		}
	}
	return ""
}

func tagTruthy(tags map[string]string, key string) bool {
	if tags == nil {
		return false
	}
	v, ok := tags[key]
	if !ok {
		return false
	}
	return v == "true" || v == "1" || v == ""
}

// goTypeToPostgres maps Go types to PostgreSQL types (legacy name; uses current dialect).
func goTypeToPostgres(kind nitroast.FieldKind, typeName string) ColumnType {
	return goTypeToSQL(kind, typeName)
}

// goTypeToSQL maps Go types to SQL column types for the active dialect.
func goTypeToSQL(kind nitroast.FieldKind, typeName string) ColumnType {
	if isJSONColumn(kind, typeName, nil) {
		return sqlJSON()
	}
	base := portableTypeBase(typeName)
	switch base {
	case "UUID":
		return sqlUUID()
	case "Date":
		return sqlDate()
	case "TimeOfDay":
		return sqlTime()
	case "DateTime":
		return sqlDateTime()
	case "Decimal":
		return sqlDecimal()
	case "Latitude", "Longitude":
		return sqlGeoCoord()
	}
	switch kind {
	case nitroast.KindString:
		if typeName == "string" {
			return TypeVarchar
		}
		return TypeText
	case nitroast.KindInt:
		switch typeName {
		case "int8", "int16", "uint8", "uint16":
			return TypeSmallInt
		case "int32", "uint32":
			return TypeInt
		case "int", "int64", "uint", "uint64":
			return TypeBigInt
		default:
			return TypeBigInt
		}
	case nitroast.KindFloat:
		switch typeName {
		case "float32":
			return TypeReal
		case "float64":
			return sqlDouble()
		default:
			return sqlDouble()
		}
	case nitroast.KindBool:
		return TypeBoolean
	case nitroast.KindTime:
		return sqlDateTime()
	case nitroast.KindSlice, nitroast.KindMap:
		return sqlJSON()
	default:
		return TypeText
	}
}

func portableTypeBase(typeName string) string {
	base := typeName
	if i := strings.IndexByte(base, '['); i >= 0 {
		base = base[:i]
	}
	if i := strings.LastIndexByte(base, '.'); i >= 0 {
		base = base[i+1:]
	}
	// strip pointer
	base = strings.TrimPrefix(base, "*")
	return base
}

func sqlUUID() ColumnType {
	switch currentDialect {
	case DialectMySQL:
		return TypeChar36
	case DialectSQLite:
		return TypeText
	case DialectSQLServer:
		return TypeUniqueIdent
	default:
		return TypeUUID
	}
}

func sqlDate() ColumnType {
	switch currentDialect {
	case DialectSQLite:
		return TypeText
	default:
		return TypeDate
	}
}

func sqlTime() ColumnType {
	switch currentDialect {
	case DialectSQLite:
		return TypeText
	default:
		return TypeTime
	}
}

func sqlDateTime() ColumnType {
	switch currentDialect {
	case DialectMySQL:
		return TypeMySQLDateTime
	case DialectSQLite:
		return TypeText
	case DialectSQLServer:
		return TypeDateTimeOffset
	default:
		return TypeTimestamp
	}
}

func sqlJSON() ColumnType {
	switch currentDialect {
	case DialectMySQL:
		return TypeMySQLJSON
	case DialectSQLite:
		return TypeText
	case DialectSQLServer:
		return TypeNVarcharMax
	default:
		return TypeJSONB
	}
}

func sqlDecimal() ColumnType {
	switch currentDialect {
	case DialectSQLite:
		return TypeText
	case DialectMySQL, DialectSQLServer:
		return TypeDecimal3810
	default:
		return TypeNumeric3810
	}
}

// sqlGeoCoord returns the highest-fidelity column for Latitude/Longitude per dialect.
func sqlGeoCoord() ColumnType {
	switch currentDialect {
	case DialectMySQL:
		return TypeDecimal129
	case DialectSQLServer:
		return TypeDecimal129
	case DialectSQLite:
		return TypeText // decimal string; SQLite has no true DECIMAL
	default:
		return TypeNumeric129
	}
}

func sqlDouble() ColumnType {
	switch currentDialect {
	case DialectMySQL, DialectSQLite:
		return TypeDoublePlain
	default:
		return TypeDouble
	}
}

func sqlNow() string {
	switch currentDialect {
	case DialectMySQL, DialectMariaDB:
		return "CURRENT_TIMESTAMP(6)"
	case DialectSQLite:
		return "CURRENT_TIMESTAMP"
	case DialectSQLServer:
		return "SYSUTCDATETIME()"
	default:
		return "NOW()"
	}
}

func sqlEmptyJSONArray() string {
	switch currentDialect {
	case DialectPostgres:
		return "'[]'::jsonb"
	default:
		return "'[]'"
	}
}

func isJSONType(t ColumnType) bool {
	switch t {
	case TypeJSONB, TypeMySQLJSON, TypeNVarcharMax:
		return true
	case TypeText:
		// SQLite stores JSON as TEXT
		return currentDialect == DialectSQLite
	default:
		return false
	}
}

func isJSONColumn(kind nitroast.FieldKind, typeName string, tags map[string]string) bool {
	if tags != nil {
		if db, ok := tags["db"]; ok {
			for _, p := range strings.Split(db, ",") {
				p = strings.TrimSpace(p)
				if strings.EqualFold(p, "jsonb") || strings.EqualFold(p, "json") {
					return true
				}
			}
		}
		blinq := parseBlinqTokens(tags["blinq"])
		if blinq["jsonb"] || blinq["json"] {
			return true
		}
	}
	base := jsonTypeBase(typeName)
	switch base {
	case "JSON", "JSONSlice", "StringSlice", "Attrs":
		return true
	}
	return kind == nitroast.KindSlice || kind == nitroast.KindMap
}

func isJSONArrayType(kind nitroast.FieldKind, typeName string) bool {
	if kind == nitroast.KindSlice {
		return true
	}
	base := jsonTypeBase(typeName)
	return base == "JSONSlice" || base == "StringSlice"
}

func jsonTypeBase(typeName string) string {
	base := typeName
	if i := strings.IndexByte(base, '['); i >= 0 {
		base = base[:i]
	}
	if i := strings.LastIndexByte(base, '.'); i >= 0 {
		base = base[i+1:]
	}
	return base
}

// isNullable checks if a column should be nullable
func isNullable(col datagen.Column) bool {
	// Soft delete field is always nullable
	if col.ColumnName == "deleted_at" {
		return true
	}
	return false
}

// formatDefault formats a default value based on its type
func formatDefault(val string, kind nitroast.FieldKind) string {
	switch kind {
	case nitroast.KindString:
		return fmt.Sprintf("'%s'", val)
	case nitroast.KindBool:
		if val == "true" || val == "1" {
			return "TRUE"
		}
		return "FALSE"
	case nitroast.KindInt, nitroast.KindFloat:
		return val
	default:
		return fmt.Sprintf("'%s'", val)
	}
}

// generateCreateTable generates a CREATE TABLE statement
func generateCreateTable(schema TableSchema) string {
	var lines []string

	lines = append(lines, fmt.Sprintf("CREATE TABLE IF NOT EXISTS %s (", schema.Name))

	for i, col := range schema.Columns {
		var parts []string
		parts = append(parts, fmt.Sprintf("    %-20s", col.Name))
		parts = append(parts, string(col.Type))

		if col.PrimaryKey {
			parts = append(parts, "PRIMARY KEY")
		}

		if col.NotNull && col.Type != TypeBigSerial {
			parts = append(parts, "NOT NULL")
		}

		if col.Unique && !col.PrimaryKey {
			parts = append(parts, "UNIQUE")
		}

		if col.Default != "" {
			parts = append(parts, fmt.Sprintf("DEFAULT %s", col.Default))
		}

		line := strings.Join(parts, " ")

		if i < len(schema.Columns)-1 {
			line += ","
		}

		lines = append(lines, line)
	}

	lines = append(lines, ");")

	for _, idx := range schema.Indexes {
		lines = append(lines, "")
		lines = append(lines, generateIndexSQL(idx, schema.Name))
	}

	return strings.Join(lines, "\n")
}
