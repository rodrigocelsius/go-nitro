package domain

import "context"

// Ctx is the request context in Nitro. It holds only pure domain
// fields, with no dependency on external infrastructure.
//
// The concrete implementation (with infrastructure fields such as
// *fasthttp.RequestCtx) lives in the adapters layer (adapters/fasthttp).
// AdapterData lets adapters store implementation-specific data
// without the domain knowing those details.
//
// Ctx is reused via sync.Pool across requests. User code must not
// keep a reference to *Ctx beyond the handler lifetime.
type Ctx struct {
	// ParamNames and ParamValues are fixed arrays (not a map) to avoid
	// allocation on the dynamic-route path. ParamCount is how many
	// slots are in use.
	ParamNames  [MaxParams]string
	ParamValues [MaxParams]string
	ParamCount  int

	// Handlers is the compiled pipeline resolved for this route.
	Handlers []Handler
	HandlerI int

	// AdapterData is a generic field for adapter data.
	// Lets adapters store infrastructure-specific data
	// (e.g. *fasthttp.RequestCtx) without the domain knowing
	// implementation details. Reset automatically by the adapter.
	AdapterData any

	// requestID is the unique request identifier, generated by the
	// RequestID middleware or taken from the X-Request-ID header.
	requestID string

	// status stores the status code when there is no adapter.
	status int

	// logger is the request-scoped logger.
	logger Logger

	// span is the request tracing span.
	span Span

	// locals are scratch values for pre/post middlewares (cleared on pool Reset).
	locals map[string]any

	// route is the matched route template (LocalHTTPRoute). Kept out of the
	// locals map so the hot path never allocates one.
	route string
}

// Param returns the route parameter value for the given name, or an empty
// string if it does not exist. Linear search on the fixed array — for
// MaxParams=8 this is faster than a map by avoiding hashing and allocation.
func (c *Ctx) Param(name string) string {
	for i := 0; i < c.ParamCount; i++ {
		if c.ParamNames[i] == name {
			return c.ParamValues[i]
		}
	}
	return ""
}

// SetParam adds a name/value parameter pair. Used internally by the
// router when matching a dynamic route.
func (c *Ctx) SetParam(name, value string) {
	if c.ParamCount >= MaxParams {
		return // silent fallback; routes with >8 params are rare
	}
	c.ParamNames[c.ParamCount] = name
	c.ParamValues[c.ParamCount] = value
	c.ParamCount++
}

// QueryParam returns a query parameter as a string.
func (c *Ctx) QueryParam(key string) string {
	// FastCtx.Query has a variadic default — match the exact signature (like HeaderParam).
	if q, ok := c.AdapterData.(interface {
		Query(string, ...string) string
	}); ok {
		return q.Query(key)
	}
	if q, ok := c.AdapterData.(interface{ Query(string) string }); ok {
		return q.Query(key)
	}
	return ""
}

// HeaderParam returns a header as a string.
func (c *Ctx) HeaderParam(key string) string {
	if c.AdapterData == nil {
		return ""
	}
	// FastCtx.Header uses a variadic default — must match the exact signature.
	if h, ok := c.AdapterData.(interface {
		Header(string, ...string) string
	}); ok {
		return h.Header(key)
	}
	if h, ok := c.AdapterData.(interface{ Header(string) string }); ok {
		return h.Header(key)
	}
	return ""
}

// Log returns the request-scoped logger.
func (c *Ctx) Log() Logger {
	if c.logger != nil {
		return c.logger
	}
	if l, ok := c.AdapterData.(interface{ Log() Logger }); ok {
		return l.Log()
	}
	return nil
}

// LoggerOrNil returns the logger set explicitly, with no AdapterData fallback.
// Used by adapters to avoid infinite recursion with Log().
func (c *Ctx) LoggerOrNil() Logger {
	return c.logger
}

// SetLogger sets the request-scoped logger.
func (c *Ctx) SetLogger(l Logger) {
	c.logger = l
}

// Method returns the HTTP request method.
func (c *Ctx) Method() string {
	if m, ok := c.AdapterData.(interface{ Method() string }); ok {
		return m.Method()
	}
	return ""
}

// Path returns the request path.
func (c *Ctx) Path() string {
	if p, ok := c.AdapterData.(interface{ Path() string }); ok {
		return p.Path()
	}
	return ""
}

// LocalHTTPRoute is the Ctx local key for the matched route template (/users/:id).
const LocalHTTPRoute = "_http_route"

// Route returns the matched route template when set by the router, else Path().
func (c *Ctx) Route() string {
	if v, ok := c.Local(LocalHTTPRoute).(string); ok && v != "" {
		return v
	}
	return c.Path()
}

// SetSpan sets the request tracing span.
func (c *Ctx) SetSpan(span Span) {
	c.span = span
}

// Span returns the request tracing span.
func (c *Ctx) Span() Span {
	return c.span
}

// SetRoute records the matched route template without boxing (hot path).
func (c *Ctx) SetRoute(route string) { c.route = route }

// SetLocal stores a scratch value for middlewares (pre → post).
func (c *Ctx) SetLocal(key string, v any) {
	if key == LocalHTTPRoute {
		if rs, ok := v.(string); ok {
			c.route = rs
			return
		}
	}
	if c.locals == nil {
		c.locals = make(map[string]any, 4)
	}
	c.locals[key] = v
}

// Local returns a middleware scratch value.
func (c *Ctx) Local(key string) any {
	if key == LocalHTTPRoute && c.route != "" {
		return c.route
	}
	if c.locals == nil {
		return nil
	}
	return c.locals[key]
}

// ClearLocals clears scratch values (called on adapter Reset).
func (c *Ctx) ClearLocals() {
	c.route = ""
	if c.locals != nil {
		clear(c.locals)
	}
}

// Status returns the HTTP status code.
func (c *Ctx) Status() int {
	return c.status
}

// RequestID returns the unique request identifier.
func (c *Ctx) RequestID() string { return c.requestID }

// SetRequestID sets the unique request identifier.
func (c *Ctx) SetRequestID(id string) { c.requestID = id }

// SetStatus sets the HTTP status code.
// Delegates to the adapter via interface; if no adapter is
// configured, stores it internally for later use.
func (c *Ctx) SetStatus(code int) {
	if s, ok := c.AdapterData.(statusSetter); ok {
		s.SetStatus(code)
		return
	}
	c.status = code
}

// SetHeader sets a response header.
func (c *Ctx) SetHeader(key, value string) {
	if s, ok := c.AdapterData.(headerSetter); ok {
		s.SetHeader(key, value)
		return
	}
}

// SetBody sets the response body.
func (c *Ctx) SetBody(data []byte) {
	if s, ok := c.AdapterData.(bodySetter); ok {
		s.SetBody(data)
		return
	}
}

// Context returns the request's context.Context.
// If none was set, it returns context.Background().
func (c *Ctx) Context() context.Context {
	if ctx, ok := c.AdapterData.(contextProvider); ok {
		return ctx.RequestContext()
	}
	return context.Background()
}

// SetContext sets the request's context.Context.
// Allows middlewares to add cancellation or deadlines.
func (c *Ctx) SetContext(ctx context.Context) {
	if cs, ok := c.AdapterData.(contextSetter); ok {
		cs.SetRequestContext(ctx)
	}
}

// contextProvider is implemented by adapters that expose the request context.
type contextProvider interface {
	RequestContext() context.Context
}

// contextSetter is implemented by adapters that allow setting the request context.
type contextSetter interface {
	SetRequestContext(ctx context.Context)
}

// statusSetter is implemented by adapters that support setting status.
type statusSetter interface {
	SetStatus(code int)
}

// headerSetter is implemented by adapters that support setting headers.
type headerSetter interface {
	SetHeader(key, value string)
}

// bodySetter is implemented by adapters that support setting the body.
type bodySetter interface {
	SetBody(data []byte)
}

// Reset clears Ctx for pool reuse. Called before each request is processed.
func (c *Ctx) Reset() {
	c.ResetHot()
	c.AdapterData = nil
}

// ResetHot clears per-request state without touching AdapterData — the adapter
// can keep a pointer to itself without nil+rewrite on the hot path.
func (c *Ctx) ResetHot() {
	c.ParamCount = 0
	c.Handlers = nil
	c.HandlerI = 0
	c.requestID = ""
	c.logger = nil
	c.span = nil
	c.status = 0
	c.route = ""
	if c.locals != nil {
		clear(c.locals) // keep capacity: no map re-allocation per request
	}
}
